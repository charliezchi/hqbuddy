"""VLA combined-mode (LA+VIO in one official VLA IP): status discovery,
combined build, native GUI entry and config-driven regeneration.

The combined IP is generated by the official VLA wizard (hq_vla_ins.exe,
same contract as IP Creator).  Its .hqip carries the full contract:
[General] LA_NUM / VLA_0={...} / VIO={...} — the wizard emits protected RTL
with HQ_VLA0/HQ_VIO attributes and probe ports the user connects in RTL.

VIO capability is NOT `insight.check has_vio` (returns 0 even for combined
builds on FT111526) — the authoritative check is the .hqip VIO section plus
the native `-vlas` export (vla.cfg vio_flag / vio.cfg), cross-checked against
the instantiated ports (P0 finding, TODO 2026-11-18).
"""

