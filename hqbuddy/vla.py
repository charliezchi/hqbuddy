# --- .hqip contract parsing -------------------------------------------------

def _extract_block(txt: str, key: str) -> str | None:
    """Extract the balanced-brace body of 'key={ ... }' (the .hqip nests
    blocks — VIO contains probe_in={...}/probe_out={...} — so a non-greedy
    regex to the first '}' truncates the section)."""
    m = re.search(re.escape(key) + r"\s*[:=]\s*\{", txt)
    if not m:
        return None
    depth = 1
    i = m.end()
    while i < len(txt) and depth:
        if txt[i] == "{":
            depth += 1
        elif txt[i] == "}":
            depth -= 1
        i += 1
    return txt[m.end():i - 1] if depth == 0 else None


def parse_hqip_combined(path: str) -> dict:
    """Parse a VLA .hqip into a contract dict; returns {} for non-VLA IPs."""
    try:
        txt = open(path, "r", encoding="utf-8", errors="replace").read()
    except OSError:
        return {}
    if "VLA_0={" not in txt:
        return {}
    out: dict = {"path": path.replace(os.sep, "/"), "la": {}, "vio": None,
                 "broken": None}
    m = re.search(r"\[General\]\s*LA_NUM:(\d+)", txt)
    out["la_num"] = int(m.group(1)) if m else None
    m = re.search(r"\[File\]\s*output_module=(\S+)", txt)
    out["module"] = m.group(1) if m else None
    if out["la_num"] is None or not out["module"]:
        out["broken"] = ("缺少 LA_NUM 或 output_module——.hqip 损坏或格式变更"
                         "（勿用 -vla -gen 新建，先修复该文件或从 wizard 重新 -modify 生成）")
    m = re.search(r"\[IP\]\s*device=(\S+)", txt)
    out["device"] = m.group(1) if m else None
    body = _extract_block(txt, "VLA_0")
    if body:
        def _g(key, cast=str):
            mm = re.search(key + r":([^\n\r]+)", body)
            return cast(mm.group(1).strip()) if mm else None
        out["la"] = {"probe_num": _g("probe_num", int),
                     "sample_depth": _g("sample_depth", int),
                     "window_num": _g("window_num", int),
                     "add_reg": _g("add_reg"),
                     "trig_pos": _g("trig_pos", int),
                     "trigger_level": _g("trigger_level", int)}
        probes = []
        for pm in re.finditer(r"probe_port_(\d+):(\d+):([^\n\r]+)", body):
            probes.append({"index": int(pm.group(1)), "width": int(pm.group(2)),
                           "type": pm.group(3).strip()})
        out["la"]["probes"] = probes
    body = _extract_block(txt, "VIO")
    if body:
        ins = [{"name": n, "width": int(w)} for n, w in
               re.findall(r"(probe_in\d+):(\d+)\s*$", body, re.M)]
        outs = [{"name": n, "width": int(w), "init": v.strip()} for n, w, v in
                re.findall(r"(probe_out\d+):(\d+):([^\n\r]+)", body)]
        out["vio"] = {"inputs": ins, "outputs": outs}
    return out


def find_combined_ips(work_dir: str) -> list:
    """All VLA .hqip files under the project tree (build dirs excluded)."""
    skip = {"hqins_run", "hq_run", "seed_sweep", "seed_sweep_ins"}
    found = []
    for base, dirs, files in os.walk(work_dir):
        dirs[:] = [d for d in dirs if d not in skip]
        for f in files:
            if f.endswith(".hqip"):
                p = os.path.join(base, f)
                c = parse_hqip_combined(p)
                if c:
                    found.append(c)
    return found


def _scan_instantiation(prj: dict, module: str | None) -> dict:
    """Scan FILE_SRC RTL for the combined-IP instantiation and its probe
    connections.  Returns {file, instance, ports: {port: signal-or-concat}}."""
    result = {"file": None, "instance": None, "ports": {}}
    if not module:
        return result
    inst_re = re.compile(
        rf"\b{re.escape(module)}\s+(\w+)\s*\(([^;]*?)\)\s*;", re.S)
    port_re = re.compile(r"\.(\w+)\s*\(\s*([^()]*?)\s*\)")
    for f in prj["sources"]:
        if not f.endswith(".v") or not os.path.isfile(f):
            continue
        txt = open(f, "r", encoding="utf-8", errors="replace").read()
        m = inst_re.search(txt)
        if not m:
            continue
        result["file"] = f.replace(os.sep, "/")
        result["instance"] = m.group(1)
        for pm in port_re.finditer(m.group(2)):
            result["ports"][pm.group(1)] = pm.group(2).strip()
        break
    return result


def _parse_module_contract(v_path: str, module: str) -> dict:
    """Parse the wizard-generated module: declared port widths and the
    HQ_VLA0/HQ_VIO synthesis attributes (the RTL-side copy of the contract).
    The .v header is non-ANSI (names in the header, declarations after)."""
    try:
        txt = open(v_path, "r", encoding="utf-8", errors="replace").read()
    except OSError:
        return {}
    m = re.search(rf"\bmodule\s+{re.escape(module)}\s*\(", txt)
    if not m:
        return {}
    body = txt[m.start():]
    m_end = re.search(r"\bendmodule\b", body)
    if m_end:
        body = body[:m_end.end()]
    ports = {}
    for pm in re.finditer(r"\b(input|output|inout)\s+(?:\[(\d+):(\d+)\]\s*)?(\w+)\s*;",
                          body):
        d, hi, lo, name = pm.group(1), pm.group(2), pm.group(3), pm.group(4)
        width = (int(hi) - int(lo) + 1) if hi is not None else 1
        ports[name] = (d, width)
    attrs = {}
    ma = re.search(r'HQ_VLA0="([^"]*)"', body)
    if ma:
        attrs["vla"] = ma.group(1)
    mv = re.search(r'HQ_VIO="([^"]*)"', body)
    if mv:
        attrs["vio"] = mv.group(1)
    return {"ports": ports, "attrs": attrs}


def _crosscheck_rtl_contract(c: dict, v_path: str, inst: dict) -> list:
    """Contract↔RTL cross-check (R3-D2): port widths, attribute numbers and
    required connections.  Returns a list of human-readable drifts ([] = ok)."""
    drifts: list = []
    mod = _parse_module_contract(v_path, c["module"])
    if not mod:
        return [f"未找到模块 {c['module']} 的定义（{v_path}）——契约无法与 RTL 互证"]
    # port widths vs contract
    for p in c["la"].get("probes", []):
        name = f"probe{p['index']}"
        w = mod["ports"].get(name, (None, None))[1]
        if w is None:
            drifts.append(f"RTL 缺少端口 {name}（.hqip 声明 {p['width']}b）")
        elif w != p["width"]:
            drifts.append(f"端口 {name} 宽度不一致: RTL {w}b vs .hqip {p['width']}b")
    vio = c["vio"]
    if vio:
        for p in vio["inputs"]:
            w = mod["ports"].get(p["name"], (None, None))[1]
            if w is None:
                drifts.append(f"RTL 缺少端口 {p['name']}（.hqip 声明 {p['width']}b）")
            elif w != p["width"]:
                drifts.append(f"端口 {p['name']} 宽度不一致: RTL {w}b vs .hqip {p['width']}b")
        for p in vio["outputs"]:
            w = mod["ports"].get(p["name"], (None, None))[1]
            if w is None:
                drifts.append(f"RTL 缺少端口 {p['name']}（.hqip 声明 {p['width']}b）")
            elif w != p["width"]:
                drifts.append(f"端口 {p['name']} 宽度不一致: RTL {w}b vs .hqip {p['width']}b")
    # attribute numbers vs contract (the RTL-side contract copy)
    avla = mod["attrs"].get("vla", "")
    for p in c["la"].get("probes", []):
        m = re.search(rf"probe{p['index']}=(\d+)", avla)
        if m and int(m.group(1)) != p["width"]:
            drifts.append(f"属性 HQ_VLA0 probe{p['index']}={m.group(1)} 与 "
                          f".hqip {p['width']}b 不一致（.v 与 .hqip 不同源？重新 -gen --config）")
    avio = mod["attrs"].get("vio", "")
    if vio:
        for p in vio["inputs"]:
            m = re.search(rf"{p['name']}=(\d+)", avio)
            if m and int(m.group(1)) != p["width"]:
                drifts.append(f"属性 HQ_VIO {p['name']}={m.group(1)} 与 "
                              f".hqip {p['width']}b 不一致")
        for p in vio["outputs"]:
            m = re.search(rf"{p['name']}=(\d+):([^ \"]+)", avio)
            if m and (int(m.group(1)) != p["width"]
                      or m.group(2).strip("'hH") != p["init"].strip("'hH")):
                drifts.append(f"属性 HQ_VIO {p['name']}={m.group(1)}:{m.group(2)} 与 "
                              f".hqip {p['width']}b init={p['init']} 不一致")
    # required connections at the instantiation site
    ports_needed = ["ref_clk", "probe0"]
    if vio:
        ports_needed += [p["name"] for p in vio["inputs"]] \
            + [p["name"] for p in vio["outputs"]]
    missing = [p for p in ports_needed if p not in inst.get("ports", {})]
    if missing:
        drifts.append("例化未连接: " + ", ".join("." + p for p in missing))
    return drifts


def _vlas_export(proj: dict, out_dir: str) -> dict | None:
    """Native discovery export: rtl.elaborate -top T -vlas <dir>/ produces
    vla.cfg / vio.cfg / vla_identity.json (GUI-equivalent of the export the
    wizard window writes).  Returns the parsed vio_flag summary or None."""
    version = _version()
    hqfpga_exe = version["hqfpga_path"]
    prj = parse_hqprj(proj["hqprj"])
    sources = [f for f in prj["sources"] if f.endswith(".v")]
    os.makedirs(out_dir, exist_ok=True)
    tcl_path = os.path.join(out_dir, "_vlas_export.tcl")
    with open(tcl_path, "w", encoding="gbk") as f:
        f.write("set vfiles {}\n")
        for f_ in sources:
            f.write(f"lappend vfiles {{{f_.replace(os.sep, '/')}}}\n")
        f.write(f"dv.setup -synlib_only {prj['family']}\n")
        f.write("rtl.analyze $vfiles\n")
        f.write(f"rtl.elaborate -top {proj['top']} -vlas "
                f"{out_dir.replace(os.sep, '/')}/\nexit\n")
    proc = subprocess.run([hqfpga_exe, "-cmd", tcl_path], cwd=out_dir,
                          capture_output=True, text=True, errors="replace",
                          timeout=300)
    cfg = {}
    vla_cfg = os.path.join(out_dir, "vla.cfg")
    vio_cfg = os.path.join(out_dir, "vio.cfg")
    for path, key in ((vla_cfg, "vla"), (vio_cfg, "vio")):
        if os.path.isfile(path):
            cfg[key] = open(path, "r", encoding="utf-8", errors="replace").read()
    if not cfg:
        return None
    m = re.search(r"vio_flag[:=](\w+)", cfg.get("vla", ""))
    cfg["vio_flag"] = m.group(1) if m else None
    cfg["dir"] = out_dir.replace(os.sep, "/")
    return cfg


def _version():
    from . import launcher
    return launcher.require_hqfpga_version()


